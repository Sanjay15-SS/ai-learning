"""Recompute every number from runs/ and write capstone/EVAL_REPORT.md + runs/summary.json.
No model calls. `python3 -m capstone report`."""
import json

from src import PRICES

from . import HERE, RUNS
from . import evaluate as E
from .obs import full_trace, read_log

# 10x assumptions (stated, not measured): in-IDE usage for 9,000 integrators
INTEGRATORS = 9000
Q_PER_DEV_DAY = 5
WORK_HOURS = 8
PEAK_FACTOR = 3


def per_question_tokens(rows):
    log = {r["trace_id"]: r for r in read_log() if r.get("kind") == "request"}
    ins, outs, calls = [], [], []
    for r in rows:
        rec = log.get(r["trace_id"])
        if not rec:
            continue
        llm_spans = [s for s in rec["spans"] if "input_tokens" in s]
        ins.append(sum(s["input_tokens"] for s in llm_spans))
        outs.append(sum(s["output_tokens"] for s in llm_spans))
        calls.append(len(llm_spans))
    n = max(len(ins), 1)
    return sum(ins) / n, sum(outs) / n, sum(calls) / n


def write_report() -> str:
    before, after = E.load_rows("before"), E.load_rows("after")
    if not after:
        return "no runs/eval_after.jsonl yet - run: python3 -m capstone eval"
    sb, sa = E.summarize(before) if before else {}, E.summarize(after)
    agree = E.judge_agreement(after)
    tax_a, tax_b = E.taxonomy(after), E.taxonomy(before) if before else []
    traj = E.trajectory(after)
    so = E.so_ablation()
    tin, tout, ncalls = per_question_tokens(after)
    lat = sa["mean_latency_s"]
    q_day = INTEGRATORS * Q_PER_DEV_DAY
    peak_qps = q_day / (WORK_HOURS * 3600) * PEAK_FACTOR
    local_qps = 1 / lat if lat else 0
    cost_at = {m: round((tin * PRICES[m][0] + tout * PRICES[m][1]) / 1e6, 5)
               for m in ("claude-haiku-4-5", "claude-sonnet-5", "claude-opus-5")}
    regress = [r for r in after if r["case_id"].startswith("R")]

    summary = {"before": sb, "after": sa, "judge_agreement": agree, "taxonomy_after": tax_a,
               "taxonomy_before": tax_b, "trajectory": {k: v for k, v in traj.items() if k != "rows"},
               "so_ablation": so,
               "cost": {"mean_cost_usd_reference": sa["mean_cost_usd"], "mean_input_tokens": round(tin),
                        "mean_output_tokens": round(tout), "mean_llm_calls": round(ncalls, 2),
                        "cost_per_question_at": cost_at},
               "tenx": {"questions_per_day": q_day, "peak_qps": round(peak_qps, 2),
                        "local_capacity_qps": round(local_qps, 4),
                        "macs_needed_at_peak": round(peak_qps / local_qps) if local_qps else None,
                        "peak_input_tokens_per_min": round(peak_qps * 60 * tin),
                        "peak_requests_per_min": round(peak_qps * 60 * ncalls),
                        "daily_cost_at_sonnet": round(q_day * cost_at["claude-sonnet-5"], 2)}}
    (RUNS / "summary.json").write_text(json.dumps(summary, indent=1))

    # the example must show the trace id crossing the MCP hop: prefer a case that called a tool
    ex = next((r for r in after if r["tools_called"]), None) or next(
        (r for r in after if r["case_id"] == "C01"), after[0])
    (HERE / "TRACE_EXAMPLE.json").write_text(json.dumps(full_trace(ex["trace_id"]), indent=1))

    L = []
    w = L.append
    w("# Eval report: integrated SDK Docs Answer Engine\n")
    w("_Generated by `python3 -m capstone report` from `capstone/runs/`. Every number below is "
      "recomputed from the run files; nothing is typed in by hand._\n")
    w(f"Model: local Qwen2.5-3B-Instruct-4bit (MLX, greedy). Corpus: synthetic `ledgerline` SDK "
      f"(v2.x + v3.0 docs, migration guide, CHANGELOG, 200 samples, 50 Stack Overflow answers, issues).\n")
    w("## 1. The number that moved: wrong-version code-sample rate\n")
    w("| | before (parts glued naively) | after (filter + code check + guards) |\n|---|---|---|")
    if sb:
        w(f"| wrong-version code samples (answers with code that fail the caller-version symbol check) "
          f"| **{sb['wrong_version_code']} = {sb['wrong_version_code_rate']:.0%}** "
          f"| **{sa['wrong_version_code']} = {sa['wrong_version_code_rate']:.0%}** |")
        w(f"| all assertions pass | {sb['symbol_checked_pass']}/{sb['n']} | {sa['symbol_checked_pass']}/{sa['n']} |")
        w(f"| mean cost / question (reference $) | ${sb['mean_cost_usd']:.5f} | ${sa['mean_cost_usd']:.5f} |")
        w(f"| mean / p95 latency | {sb['mean_latency_s']}s / {sb['p95_latency_s']}s | {sa['mean_latency_s']}s / {sa['p95_latency_s']}s |")
    w(f"\nn = {sa['n']} cases (same cases, same model, same prompts; `before` = no metadata "
      "filter, Stack Overflow shown raw, no code check, no guards).\n")
    w("**Pass rate per category (assertions):**\n")
    w("| category | before | after |\n|---|---|---|")
    for k in sa["pass_by_category"]:
        w(f"| {k} | {sb.get('pass_by_category', {}).get(k, '-')} | {sa['pass_by_category'][k]} |")
    w("\n### Bonus: what happens when 'looks like code' stops counting\n")
    if sb:
        w(f"Before: **{sb['looks_like_code_pass']}/{sb['n']}** answers pass every other assertion with a "
          f"code block that merely parses. With the parse + import + symbol-table + kwargs check against the "
          f"caller's version, **{sb['red_once_looks_like_code_stops_counting']}** of those go red "
          f"→ {sb['symbol_checked_pass']}/{sb['n']}.\n")
    w("## 2. Judge, re-checked on integrated outputs\n")
    w(f"Judge pass rate (after): {sa['judge_pass_rate']}. Agreement with hand labels: "
      f"`{json.dumps(agree)}`\n")
    w("The judge scores ONE thing assertions cannot (does the answer actually address the question, "
      "correctly). Code validity, version, citations, deprecations, and removed-method phrasing are "
      "assertions, never judged.\n")
    w("## 3. Re-scored error taxonomy (after)\n")
    w("| mode | count | freq % | severity | one trace id |\n|---|---|---|---|---|")
    for t in tax_a:
        tag = " **(NEW: created by integration)**" if t["mode"] in (
            "version_dropped_at_mcp_hop", "guard_withheld_needed_code", "redactor_corrupts_code", "truncated_code_unchecked", "prose_contradicts_withheld_code") else ""
        w(f"| {t['mode']}{tag} | {t['count']} | {t['freq_pct']} | {t['severity']} | `{t['trace_id']}` |")
    w("| redactor_corrupts_code **(NEW: created by integration)** | found in dev, fixed before the eval run | - | high | "
      "`trc12_d54345f79f9e` (runs/found_redactor_corrupts_code.jsonl) |")
    if tax_b:
        w("\nBefore, for comparison:\n\n| mode | count | freq % | trace id |\n|---|---|---|---|")
        for t in tax_b:
            w(f"| {t['mode']} | {t['count']} | {t['freq_pct']} | `{t['trace_id']}` |")
    w("\n## 4. Trajectory eval (after)\n")
    w(f"n = {traj.get('n')}. Tool-choice accuracy **{traj.get('tool_choice_accuracy')}**, trajectory pass "
      f"{traj.get('trajectory_pass')}, outcome pass {traj.get('outcome_pass')}, "
      f"**outcome − trajectory gap = {traj.get('outcome_minus_trajectory_gap')}**. Cases where the agent called "
      f"no tool at all: {traj.get('no_tool_called')}.\n")
    w(f"- outcome OK but trajectory wrong (the guards rescued it): {traj.get('outcome_ok_but_trajectory_wrong')}")
    w(f"- trajectory OK but outcome wrong: {traj.get('trajectory_ok_but_outcome_wrong')}\n")
    w("## 5. Stack Overflow: keep, drop, or bridge? (retrieval hit@4 on gold pages, no LLM)\n")
    w("| SO handling | hit@4 | cases with SO text in context | cases with a wrong-version chunk |\n|---|---|---|---|")
    for k, v in so.items():
        w(f"| {k} | {v['hit_at_4']} ({v['hit_rate']:.0%}) | {v['cases_with_SO_text_in_context']} | {v['cases_with_wrong_version_chunk']} |")
    w("\nDropping SO removes the poison and costs recall; the bridge keeps SO for MATCHING only and "
      "swaps every SO hit for its linked doc page in the caller's version.\n")
    w("## 6. Closed failure→test loop\n")
    if regress:
        for r in regress:
            w(f"- `{r['case_id']}` (promoted word for word from trace `trc12_d54345f79f9e`): "
              f"{'PASS' if r['assert_pass'] else 'FAIL'} in the after run, trace `{r['trace_id']}`")
    w("- Live: `python3 -m capstone loop` runs it with the code-check guard OFF (red) then ON (green).\n")
    w("## 7. Cost per question and the 10× plan\n")
    w(f"- Mean per question (after): {ncalls:.2f} LLM calls, {tin:.0f} input + {tout:.0f} output tokens.")
    w(f"- Cost per question: $0 actual (local). Same tokens at list prices: "
      + ", ".join(f"{m} ${c}" for m, c in cost_at.items()) + ".")
    t = summary["tenx"]
    w(f"- 9,000 integrators × {Q_PER_DEV_DAY} q/day (assumption) = {t['questions_per_day']:,} q/day; "
      f"peak ({PEAK_FACTOR}× the {WORK_HOURS}h average) = **{t['peak_qps']} q/s**.")
    w(f"- **What breaks first: serving throughput.** One Mac answers {t['local_capacity_qps']} q/s "
      f"(mean latency {lat}s, serial). Peak needs ~**{t['macs_needed_at_peak']}×** that. Moving to an API "
      f"needs ~{t['peak_requests_per_min']:,} requests/min and ~{t['peak_input_tokens_per_min']:,} input "
      f"tokens/min at peak: compare those two numbers against the org's rate-limit tier before launch. "
      f"Daily cost at Sonnet-class prices ≈ ${t['daily_cost_at_sonnet']:,}.")
    w(f"- Second: latency. p95 {sa['p95_latency_s']}s is unusable in an IDE; the repair call adds a full LLM round-trip on every wrong-code answer.\n")
    w("## 8. What this suite does NOT cover\n")
    w("- It never EXECUTES code against a real SDK install: the symbol table is our model of the SDK. If "
      "sdk_spec.py is wrong, the check is confidently wrong too.\n"
      "- Runtime semantics beyond symbols: wrong argument VALUES, wrong types, logic bugs (e.g. an infinite "
      "pagination loop) all pass.\n"
      "- Only Python; only the `ledgerline` SDK; 30 cases + regressions, authored by us, on a synthetic corpus.\n"
      "- Retrieval quality is measured as hit@4 on gold pages only, not ranking.\n"
      "- Multi-turn conversations, and questions whose version changes mid-thread.\n"
      "- The judge is a 3B local model; its agreement number is only as good as the labels behind it.\n")
    md = "\n".join(L)
    (HERE / "EVAL_REPORT.md").write_text(md)
    from .results_md import write_results
    write_results(summary)
    return md
