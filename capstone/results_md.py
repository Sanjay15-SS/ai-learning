"""Write RESULTS-week12.md (repo root) in the same shape as RESULTS-week6..11.md.
Every number is read from capstone/runs/ - run `python3 -m capstone report` to regenerate."""
import json

from . import HERE, RUNS
from . import evaluate as E

ROOT = HERE.parent


def _row(rows, cid):
    return next((r for r in rows if r["case_id"] == cid), None)


def _snip(text, n=1400):
    text = text or ""
    return text if len(text) <= n else text[:n] + "\n…(truncated)"


def write_results(summary: dict) -> str:
    before, after = E.load_rows("before"), E.load_rows("after")
    sb, sa = summary["before"], summary["after"]
    agree, traj, so = summary["judge_agreement"], summary["trajectory"], summary["so_ablation"]
    cost, tenx = summary["cost"], summary["tenx"]
    loop = json.loads((RUNS / "loop.json").read_text()) if (RUNS / "loop.json").exists() else None
    tr = json.loads((HERE / "TRACE_EXAMPLE.json").read_text()) if (HERE / "TRACE_EXAMPLE.json").exists() else {}
    req = tr.get("request") or {}
    found = json.loads((RUNS / "found_redactor_corrupts_code.jsonl").read_text().splitlines()[0])
    c01b, c01a, c11a = _row(before, "C01"), _row(after, "C01"), _row(after, "C11")
    new_modes = ("version_dropped_at_mcp_hop", "guard_withheld_needed_code", "redactor_corrupts_code")

    L = []
    w = L.append
    w("# Week 12 Capstone — Task Set E Results\n")
    w("## SDK Docs Answer Engine (Variant E)")
    w("**Domain**: Developer documentation (`ledgerline` Python SDK, v2.4 + v3.0 both live)  ")
    w("**Module**: M6 — end-to-end app + closed loop  ")
    w("**Code**: [`capstone/`](capstone/README.md) · **One command**: `python3 -m capstone all --subset`  ")
    w(f"**Model**: local Qwen2.5-3B-Instruct-4bit (MLX, greedy) on an 8 GB Apple M1 · "
      f"**n** = {sa['n']} cases (12-case subset covering every category; the full 30 resume with "
      "`python3 -m capstone eval`)\n")
    w("> Generated by `capstone/results_md.py` from `capstone/runs/`. No number is typed by hand.\n")
    w("---\n")

    w("## 1. Problem Statement (Executive Summary)\n")
    w("~40% of 9,000 integrators are still on SDK 2.x. v3.0 renamed `client.query()` → `client.search()` "
      "(`page_token` → `cursor`) and made `Client(timeout=...)` required, so a v3 snippet handed to a v2.4 "
      "caller imports cleanly, passes review, and fails in production. The system resolves the caller's "
      "version **before** retrieval, filters retrieval on version **metadata in code**, runs every emitted "
      "sample through a **parser + symbol-table check for that version**, surfaces deprecations unasked, cites "
      "every page with its version, and says \"`X` no longer exists in 3.0 — here is the migration\" instead "
      "of inventing a signature.\n")
    if sb:
        w(f"**Headline:** wrong-version code-sample rate **{sb['wrong_version_code']} ({sb['wrong_version_code_rate']:.0%})"
          f" → {sa['wrong_version_code']} ({sa['wrong_version_code_rate']:.0%})**; all-assertion pass "
          f"**{sb['symbol_checked_pass']}/{sb['n']} → {sa['symbol_checked_pass']}/{sa['n']}**.\n")
    w("---\n")

    w("## 2. Failure-Finding & Error Analysis (30 pts)\n")
    w("### Re-scored error taxonomy — integrated system (after)\n")
    w("| Mode | Count | Freq % | Severity | Trace id |\n|---|---|---|---|---|")
    for t in summary["taxonomy_after"]:
        tag = " 🆕 **integration-created**" if t["mode"] in new_modes else ""
        w(f"| `{t['mode']}`{tag} | {t['count']} | {t['freq_pct']}% | {t['severity']} | `{t['trace_id']}` |")
    w("| `redactor_corrupts_code` 🆕 **integration-created** | found in dev, fixed before the run | — | high | "
      "`trc12_d54345f79f9e` |")
    if summary["taxonomy_before"]:
        w("\n**Before (parts glued naively), same cases:**\n")
        w("| Mode | Count | Freq % | Trace id |\n|---|---|---|---|")
        for t in summary["taxonomy_before"]:
            w(f"| `{t['mode']}` | {t['count']} | {t['freq_pct']}% | `{t['trace_id']}` |")
    w("\n### The mode integration created: the redactor corrupts generated code\n")
    w("Week 11's redact-on-write is correct alone; Week 3–7's answer generator is correct alone. Joined, the "
      "`token=` secret rule ran over the **answer** and turned working code into broken code:\n")
    w("```python\n" + "\n".join(l for l in found["answer"].splitlines() if "REDACTED" in l) + "\n```")
    w(f"Trace `{found['trace_id']}` (`capstone/runs/found_redactor_corrupts_code.jsonl`). Fix: secret rules match "
      "quoted literals only; `selftest #7` asserts `page_token=page_token` survives redaction.\n")
    w("### Traces actually read\n")
    w(f"1. `{found['trace_id']}` — v2.4 caller, **first draft used v3 `client.search(..., cursor=)`** even with the "
      "version filter on (the model \"helpfully upgraded\" because the v2 page mentions the 3.0 rename). "
      "`code_check` caught it, `repair` fixed it. Raw draft:\n")
    w("```python\n" + "\n".join(l for l in found["raw_answer"].splitlines() if "client." in l or "import" in l) + "\n```")
    w("2. `trc12_84700673c026` — C30 \"async client\": answer wrapped `client.search()` in `async for`. Symbol check "
      "passed (the method exists), **the 3B judge passed it**. Added an async-misuse rule to `codecheck.py`.")
    if c01b:
        w(f"3. `{c01b['trace_id']}` — C01 before: failed {[k for k, v in c01b['assertions'].items() if not v]}.")
    w("\n### Top-3 weaknesses (written Wednesday 2026-11-25, before the run) — [`capstone/WEAKNESSES.md`](capstone/WEAKNESSES.md)\n")
    w("1. The code check trusts a symbol table we wrote, not the released SDK.")
    w("2. The agent mostly doesn't verify; the deterministic guards do.")
    w("3. Version resolution is a regex over the question; unstated version defaults to 3.0.\n")
    w("---\n")

    w("## 3. A Number That Moved (25 pts)\n")
    w("| Metric | Before | After |\n|---|---|---|")
    if sb:
        w(f"| **Wrong-version code-sample rate** | **{sb['wrong_version_code']} = {sb['wrong_version_code_rate']:.0%}** "
          f"| **{sa['wrong_version_code']} = {sa['wrong_version_code_rate']:.0%}** |")
        w(f"| All assertions pass | {sb['symbol_checked_pass']}/{sb['n']} | {sa['symbol_checked_pass']}/{sa['n']} |")
        w(f"| Mean cost / question (reference) | ${sb['mean_cost_usd']:.5f} | ${sa['mean_cost_usd']:.5f} |")
        w(f"| Mean / p95 latency | {sb['mean_latency_s']}s / {sb['p95_latency_s']}s | {sa['mean_latency_s']}s / {sa['p95_latency_s']}s |")
    w(f"\nn = {sa['n']}. Same model, same prompts. *Before* = no metadata filter, Stack Overflow shown raw, no code "
      "check, no guards. *After* = filter in code, SO as matching bridge, `sdk_version` pinned at the MCP hop, "
      "parse + symbol check + one repair, deprecation and removed-method guards.\n")
    w("**Pass rate per category:**\n")
    w("| Category | Before | After |\n|---|---|---|")
    for k in sa["pass_by_category"]:
        w(f"| {k} | {sb.get('pass_by_category', {}).get(k, '-')} | {sa['pass_by_category'][k]} |")
    w("\n### Judge agreement on integrated outputs\n")
    if "agreement" in agree:
        ok = "✅ clears 85%" if agree["agreement"] >= 0.85 else "❌ below 85% — judge needs another iteration"
        w(f"**{agree['agreement']:.0%}** on n={agree['n']} vs hand labels by `{agree['labeler']}` — {ok}. "
          f"Human-FAIL caught by judge: {agree['human_fail_caught_by_judge']}. Disagreements: {agree['disagreements']}.\n")
    else:
        w(f"**Pending hand labels** — `{agree.get('status')}`. Judge pass rate on after outputs: "
          f"{sa['judge_pass_rate']}. Run `python3 -m capstone label` then `python3 -m capstone report`.\n")
    w("The judge scores only *does it correctly answer the question*. Code validity, version, citations, "
      "deprecations and removed-method phrasing are assertions — never judged.\n")
    w("### What this suite does NOT cover\n")
    w("It never **executes** code against a real `pip install ledgerline==2.4.1` — the symbol table is our model "
      "of the SDK, so if `sdk_spec.py` is wrong the check is confidently wrong. Also uncovered: argument *values* "
      "and logic bugs, non-Python callers, multi-turn threads, and ranking quality beyond hit@4.\n")
    w("---\n")

    w("## 4. Integration Completeness (20 pts)\n")
    w("| Requirement | Where | Evidence |\n|---|---|---|")
    w("| RAG behind one entry point, version-cited links | `engine.py` → `retriever.py` | `Sources:` lines carry `(v2.x)` / `(v3.0)` |")
    w("| Hand-built agent loop, ≥3 tools, MCP tools discovered at runtime | `engine.py` `MCPSession` (tools/list) | selftest #8 |")
    w("| Own MCP server, genuine capability | `mcp_server.py`: `search_sdk_docs`, `lookup_changelog`, `symbol_exists`, `check_code` | `python3 -m capstone mcp`; outside client → [`FRESH_EYES.md`](capstone/FRESH_EYES.md) |")
    w(f"| Eval suite, one command, assertions before judge | `evaluate.py` | n={sa['n']} |")
    w("| Taxonomy re-scored, ≥1 NEW mode | §2 | `redactor_corrupts_code`, `version_dropped_at_mcp_hop` |")
    w(f"| Trajectory eval ≥10 cases | §6 | n={traj.get('n')} |")
    w("| One trace id across agent + MCP hops, cost/latency per span, PII redacted on write | `obs.py`, `mcp_server.py` (`_meta.trace_id`) | below |")
    w("| Closed failure→test loop | `loop.py`, `evals/regressions.jsonl` | §7 |")
    if req:
        w(f"\n### One end-to-end trace — `{req['trace_id']}` ([`capstone/TRACE_EXAMPLE.json`](capstone/TRACE_EXAMPLE.json))\n")
        w("| Span | Latency (s) | Tokens in/out | Cost (USD) |\n|---|---|---|---|")
        for s in req["spans"]:
            tok = f"{s['input_tokens']}/{s['output_tokens']}" if "input_tokens" in s else "—"
            w(f"| `{s['span']}` | {s['latency_s']} | {tok} | ${s.get('cost_usd', 0):.6f} |")
        for s in tr.get("mcp_server_spans", []):
            w(f"| ↳ `{s['span']}` (MCP server process, same trace id) | {s['latency_s']} | — | $0 |")
        w(f"| **total** | **{req['total_latency_s']}** | | **${req['total_cost_usd']:.6f}** |")
    w("\nPII: `redact()` runs on the question before the model sees it and again on every string at write time "
      "(API keys, DSNs, bearer tokens, `whsec_` secrets, emails). Cases C28/C29 assert the pasted secrets are "
      "absent from the log line.\n")
    w("---\n")

    w("## 5. Application Depth (15 pts)\n")
    if c01a:
        w(f"**C01 — \"I'm on 2.4 - how do I paginate…\"** (`{c01a['trace_id']}`): version "
          f"`{c01a['version']['version']}` from `{c01a['version']['source']}` before retrieval.\n")
        w("```text\n" + _snip(c01a["answer"]) + "\n```\n")
    if c11a:
        w(f"**C11 — \"How do I call client.query() in 3.0?\"** (`{c11a['trace_id']}`):\n")
        w("```text\n" + _snip(c11a["answer"].split("```")[0].strip(), 600) + "\n```\n")
    w("---\n")

    w("## 6. Trajectory Eval (outcome vs trajectory)\n")
    w("| Metric | Value |\n|---|---|")
    for k in ("n", "tool_choice_accuracy", "trajectory_pass", "outcome_pass", "outcome_minus_trajectory_gap",
              "no_tool_called"):
        w(f"| {k} | **{traj.get(k)}** |")
    w(f"\nOutcome OK but trajectory wrong (guards rescued it): {traj.get('outcome_ok_but_trajectory_wrong')}  ")
    w(f"Trajectory OK but outcome wrong: {traj.get('trajectory_ok_but_outcome_wrong')}\n")
    w("---\n")

    w("## 7. Iteration Thinking (10 pts)\n")
    w("### Closed failure → test loop (live: `python3 -m capstone loop`)\n")
    if loop:
        c = loop["case"]
        w(f"Case `{c['id']}` promoted **word for word** from trace `{c['source'][6:]}` → `capstone/evals/regressions.jsonl`:\n")
        w(f"> {c['question']}\n")
        w("| Run | Result | Trace id | Failed assertions |\n|---|---|---|---|")
        for r in loop["runs"]:
            w(f"| {r['label']} | **{r['result']}** | `{r['trace_id']}` | {r['failed'] or '—'} |")
    else:
        w("_Pending — `python3 -m capstone loop` has not been run yet._")
    w("\n### Cost per question\n")
    w(f"{cost['mean_llm_calls']} LLM calls, {cost['mean_input_tokens']} input + {cost['mean_output_tokens']} output "
      f"tokens per question. Actual spend $0 (local). Same tokens at list prices: "
      + ", ".join(f"{m} **${v}**" for m, v in cost["cost_per_question_at"].items()) + ".\n")
    w("### 10× plan — what breaks first in-IDE for 9,000 integrators\n")
    w("| Factor | Number |\n|---|---|")
    w(f"| Questions/day (9,000 × 5, assumption) | {tenx['questions_per_day']:,} |")
    w(f"| Peak (3× the 8 h average) | **{tenx['peak_qps']} q/s** |")
    w(f"| One M1 serves | {tenx['local_capacity_qps']} q/s |")
    w(f"| **Shortfall → serving throughput breaks first** | **~{tenx['macs_needed_at_peak']}× capacity needed** |")
    w(f"| On an API at peak | {tenx['peak_requests_per_min']:,} req/min, {tenx['peak_input_tokens_per_min']:,} input tok/min — check against the org's rate-limit tier |")
    w(f"| Daily cost at Sonnet-class prices | ${tenx['daily_cost_at_sonnet']:,} |")
    w("\n**v3.1 next month (two more deprecations):** re-indexing is BM25 in memory, < 1 s, $0. "
      "`selftest #9` goes **red the morning `sdk_spec.py` gains a deprecated symbol with no eval case**.\n")
    w("### Ranked next steps\n")
    w("1. Generate `sdk_spec.py` from the released wheel in CI — ~1 day — kills weakness #1.")
    w("2. Read the SDK version from the IDE lockfile instead of prose — ~0.5 day — kills weakness #3.")
    w("3. Move serving to an API or batch GPU host — the 10× blocker.")
    w("4. Stop sequence + dedupe for doubled answers (seam #10) — ~1 h.\n")
    w("---\n")

    w("## 8. Bonus — Stop Judging Code, Execute the Check\n")
    if sb:
        w(f"Before: **{sb['looks_like_code_pass']}/{sb['n']}** answers pass with \"looks like code\" (a block that parses). "
          f"With parse + imports + symbol table + kwargs for the caller's version, **{sb['red_once_looks_like_code_stops_counting']}** "
          f"of them go **red** → {sb['symbol_checked_pass']}/{sb['n']}.\n")
    w("### Stack Overflow: keep, drop or bridge? (hit@4 on gold pages, 29 cases, no LLM)\n")
    w("| SO handling | hit@4 | SO text in context | wrong-version chunk retrieved |\n|---|---|---|---|")
    for k, v in so.items():
        w(f"| {k} | {v['hit_at_4']} ({v['hit_rate']:.0%}) | {v['cases_with_SO_text_in_context']} | {v['cases_with_wrong_version_chunk']} |")
    w("\n---\n")

    w("## 9. Submission Deliverables\n")
    w("| Deliverable | File | Status |\n|---|---|---|")
    items = [("One command + README", "capstone/README.md", "✅"),
             ("Seam list, each marked fixed / accepted / ran-out-of-time", "capstone/SEAMS.md", "✅"),
             ("One-page architecture sketch", "capstone/ARCHITECTURE.md", "✅"),
             ("Eval output: pass rate per mode, n, judge agreement", "capstone/EVAL_REPORT.md",
              "✅" if "agreement" in agree else "⏳ judge agreement pending hand labels"),
             ("Re-scored taxonomy with integration-created mode", "§2", "✅"),
             ("Trajectory eval + gap", "§6", "✅"),
             ("End-to-end trace, cost + latency per span", "capstone/TRACE_EXAMPLE.json", "✅"),
             ("Top-3 weaknesses dated Wednesday", "capstone/WEAKNESSES.md", "✅"),
             ("Cost per question + 10× plan", "§7", "✅"),
             ("Fresh-eyes note", "capstone/FRESH_EYES.md", "⏳ filled by Thursday reviewer"),
             ("10-minute demo script", "capstone/DEMO_SCRIPT.md", "✅")]
    for a, b, c in items:
        w(f"| {a} | `{b}` | {c} |")
    w("\n---\n")
    w("## 10. What Each Number Means\n")
    w("- **Wrong-version code-sample rate** — of answers containing code, the share whose code fails the parse + "
      "import + symbol + kwargs check for the caller's version. Deterministic; no judge.")
    w("- **Judge agreement** — share of cases where the LLM judge's PASS/FAIL equals the human label.")
    w("- **Tool-choice accuracy** — share of cases where the agent called at least one tool from the case's expected set.")
    w("- **Outcome − trajectory gap** — outcome pass rate minus trajectory pass rate; positive = guards rescued "
      "answers the agent didn't verify.")
    w("- **hit@4** — share of cases where a gold page is in the top 4 retrieved chunks.")
    w("- **Cost (reference)** — local tokens priced at Claude Haiku 4.5 list rates; actual spend $0.")
    md = "\n".join(L) + "\n"
    (ROOT / "RESULTS-week12.md").write_text(md)
    return md
